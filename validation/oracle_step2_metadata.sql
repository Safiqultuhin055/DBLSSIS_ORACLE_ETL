-- Step 2: Oracle target validation (READ-ONLY: SELECT statements only)
-- Run from this folder:
--   sqlplus -L ORACLE_LOGIN@//ORACLE_HOST:ORACLE_PORT/ORACLE_SERVICE @oracle_step2_metadata.sql
-- Output: out_oracle_step2.csv (same folder). Contains no credentials.

WHENEVER SQLERROR CONTINUE
SET ECHO OFF
SET FEEDBACK OFF
SET VERIFY OFF
SET PAGESIZE 50000
SET LINESIZE 400
SET MARKUP CSV ON QUOTE ON
SPOOL out_oracle_step2.csv

PROMPT ===ORA_IDENTITY
SELECT SYS_CONTEXT('USERENV','DB_NAME')      AS DB_NAME,
       SYS_CONTEXT('USERENV','SERVICE_NAME') AS SERVICE_NAME,
       SYS_CONTEXT('USERENV','SESSION_USER') AS SESSION_USER,
       (SELECT VALUE FROM NLS_DATABASE_PARAMETERS WHERE PARAMETER = 'NLS_CHARACTERSET')       AS DB_CHARSET,
       (SELECT VALUE FROM NLS_DATABASE_PARAMETERS WHERE PARAMETER = 'NLS_NCHAR_CHARACTERSET') AS NCHAR_CHARSET,
       (SELECT VALUE FROM NLS_DATABASE_PARAMETERS WHERE PARAMETER = 'NLS_RDBMS_VERSION')      AS RDBMS_VERSION
FROM DUAL;

PROMPT ===ORA_ACCOUNT
SELECT USERNAME, ACCOUNT_STATUS, LOCK_DATE, PROFILE FROM USER_USERS;

PROMPT ===ORA_PASSWORD_LIMITS
SELECT RESOURCE_NAME, LIMIT
FROM USER_PASSWORD_LIMITS
WHERE RESOURCE_NAME IN ('FAILED_LOGIN_ATTEMPTS', 'PASSWORD_LOCK_TIME');

PROMPT ===ORA_COLUMNS
SELECT COLUMN_ID, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, CHAR_LENGTH, CHAR_USED,
       DATA_PRECISION, DATA_SCALE, NULLABLE, DATA_DEFAULT
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'APPS'
  AND TABLE_NAME = 'ETL_BATCH_SQL_STG'
ORDER BY COLUMN_ID;

PROMPT ===ORA_ROWCOUNT
SELECT COUNT(*) AS TARGET_ROWS FROM APPS.ETL_BATCH_SQL_STG;

PROMPT ===ORA_CONSTRAINTS
SELECT c.CONSTRAINT_NAME, c.CONSTRAINT_TYPE, c.STATUS, cc.COLUMN_NAME, cc.POSITION
FROM ALL_CONSTRAINTS c
JOIN ALL_CONS_COLUMNS cc
  ON cc.OWNER = c.OWNER AND cc.CONSTRAINT_NAME = c.CONSTRAINT_NAME
WHERE c.OWNER = 'APPS'
  AND c.TABLE_NAME = 'ETL_BATCH_SQL_STG'
ORDER BY c.CONSTRAINT_NAME, cc.POSITION;

PROMPT ===ORA_INDEXES
SELECT i.INDEX_NAME, i.UNIQUENESS, ic.COLUMN_NAME, ic.COLUMN_POSITION
FROM ALL_INDEXES i
JOIN ALL_IND_COLUMNS ic
  ON ic.INDEX_OWNER = i.OWNER AND ic.INDEX_NAME = i.INDEX_NAME
WHERE i.TABLE_OWNER = 'APPS'
  AND i.TABLE_NAME = 'ETL_BATCH_SQL_STG'
ORDER BY i.INDEX_NAME, ic.COLUMN_POSITION;

PROMPT ===ORA_TRIGGERS
SELECT TRIGGER_NAME, TRIGGER_TYPE, TRIGGERING_EVENT, STATUS
FROM ALL_TRIGGERS
WHERE TABLE_OWNER = 'APPS'
  AND TABLE_NAME = 'ETL_BATCH_SQL_STG';

PROMPT ===END
SPOOL OFF
EXIT
