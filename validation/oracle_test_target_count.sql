-- Read-only test of the fixed ORACLE_TARGET_ROW_COUNT query (no DML).
SET PAGESIZE 50 LINESIZE 200 FEEDBACK ON
SELECT TO_CHAR(t.CNT) AS TARGET_ROWS, TO_CHAR(d.CNT) AS TARGET_DUP_KEYS
FROM (SELECT COUNT(*) AS CNT FROM APPS.ETL_BATCH_SQL_STG) t
CROSS JOIN (SELECT COUNT(*) AS CNT FROM (SELECT BATCHNO FROM APPS.ETL_BATCH_SQL_STG
            WHERE BATCHNO IS NOT NULL GROUP BY BATCHNO HAVING COUNT(*) > 1)) d;
EXIT
